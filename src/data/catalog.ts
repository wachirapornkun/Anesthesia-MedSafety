export function isHadDrug(item: {
  isHad?: boolean;
  category?: DrugCategory;
  name?: string;
  drugName?: string;
  genericName?: string;
}): boolean {
  if (item.isHad === true || item.category === 'had') return true;
  const combined = `${item.name || ''} ${item.drugName || ''} ${item.genericName || ''}`.toLowerCase();
  return HAD_KEYWORDS.some((kw) => combined.includes(kw));
}

